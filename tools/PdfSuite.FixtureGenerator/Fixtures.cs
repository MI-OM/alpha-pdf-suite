using System.Text;
using PdfSuite.Pdf.Pdfium.Authoring;
using PdfSuite.Pdf.Qpdf;

namespace PdfSuite.FixtureGenerator;

/// <summary>
/// Describes one generated fixture for the manifest. Rectangles are
/// [left, bottom, right, top] in PDF points, origin bottom-left.
/// </summary>
public sealed record FixtureInfo(
    string File,
    string Description,
    string? Canary = null,
    string? CanaryLocation = null,
    int? RedactPage = null,
    double[]? RedactRect = null,
    int[]? CanaryRemainsOnPages = null,
    string[]? DocumentLevelCanaries = null)
{
    public string Provenance => Fixtures.Provenance;
}

public sealed record Fixture(FixtureInfo Info, Func<byte[]> Generate);

/// <summary>
/// Synthetic test documents built only with PDFium, so they carry no third-party content.
/// Output is byte-for-byte reproducible (see <see cref="Reproducible"/>).
/// Document-level canaries (metadata, JavaScript, bookmarks, structure tree, hidden layer) are added
/// with qpdf, which writes what PDFium cannot.
/// </summary>
public static class Fixtures
{
    public const string Provenance = "Synthetic. Generated by tools/PdfSuite.FixtureGenerator; contains no third-party content.";

    public const int LargePageCount = 2000;

    private const double LetterWidth = 612;
    private const double LetterHeight = 792;

    // FPDFPage_GenerateContent takes time proportional to the document's page count, so
    // building 2,000 pages in one document is quadratic (94 s measured). Building 100-page
    // chunks and importing them keeps generation close to linear (spike S0 finding).
    private const int ChunkSize = 100;

    // Canary text is set at 12 pt Helvetica from x = 180; "CANARY-nn" is about 67 pt wide.
    private static readonly double[] CanaryLineRect = [176, 494, 252, 514];

    private static readonly string[] Words =
    [
        "document", "review", "quarterly", "figure", "summary", "account", "report", "section",
        "analysis", "schedule", "appendix", "record", "policy", "update", "table", "result",
        "method", "sample", "archive", "index",
    ];

