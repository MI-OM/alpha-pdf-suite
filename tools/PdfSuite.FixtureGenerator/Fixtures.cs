using System.Text;
using PdfSuite.Pdf.Pdfium.Authoring;

namespace PdfSuite.FixtureGenerator;

/// <summary>
/// Describes one generated fixture for the manifest. Rectangles are
/// [left, bottom, right, top] in PDF points, origin bottom-left.
/// </summary>
public sealed record FixtureInfo(
    string File,
    string Description,
    string? Canary = null,
    string? CanaryLocation = null,
    int? RedactPage = null,
    double[]? RedactRect = null,
    int[]? CanaryRemainsOnPages = null)
{
    public string Provenance => Fixtures.Provenance;
}

public sealed record Fixture(FixtureInfo Info, Func<byte[]> Generate);

/// <summary>
/// Synthetic test documents built only with PDFium, so they carry no third-party content.
/// Output is byte-for-byte reproducible (see <see cref="Reproducible"/>).
/// The canary set covers the locations PDFium can write. Metadata, JavaScript, bookmark,
/// hidden-layer, vector-art and password fixtures need qpdf and arrive with spike items S4 and S5.
/// </summary>
public static class Fixtures
{
    public const string Provenance = "Synthetic. Generated by tools/PdfSuite.FixtureGenerator; contains no third-party content.";

    public const int LargePageCount = 2000;

    private const double LetterWidth = 612;
    private const double LetterHeight = 792;

    // FPDFPage_GenerateContent takes time proportional to the document's page count, so
    // building 2,000 pages in one document is quadratic (94 s measured). Building 100-page
    // chunks and importing them keeps generation close to linear (spike S0 finding).
    private const int ChunkSize = 100;

    // Canary text is set at 12 pt Helvetica from x = 180; "CANARY-nn" is about 67 pt wide.
    private static readonly double[] CanaryLineRect = [176, 494, 252, 514];

    private static readonly string[] Words =
    [
        "document", "review", "quarterly", "figure", "summary", "account", "report", "section",
        "analysis", "schedule", "appendix", "record", "policy", "update", "table", "result",
        "method", "sample", "archive", "index",
    ];

    public static IReadOnlyList<Fixture> All { get; } =
    [
        new(new("simple-text.pdf", "Three Letter pages of plain text."), SimpleText),
        new(new(
            "large-2000-pages.pdf",
            "2,000 pages: Letter portrait, every 10th page landscape, every 50th page A4; text, rectangles, and an image every 25th page."),
            () => LargeMixed()),
        new(new(
            "canary-text.pdf", "Canary in a text object.",
            "CANARY-01", "text", 0, CanaryLineRect), CanaryText),
        new(new(
            "canary-image.pdf", "Canary drawn as pixels inside an image; it is not extractable text.",
            "CANARY-02", "image", 0, [70, 398, 274, 442]), CanaryImage),
        new(new(
            "canary-shared-xobject.pdf", "Canary in a form XObject shared by pages 1 and 2. Only page 1 is redacted.",
            "CANARY-03", "shared form XObject", 0, [70, 598, 274, 642], [1]), CanarySharedXObject),
        new(new(
            "canary-annotation.pdf", "Canary in the comment of a sticky-note annotation.",
            "CANARY-04", "annotation contents", 0, [296, 596, 324, 624]), CanaryAnnotation),
        new(new(
            "canary-attachment.pdf", "Canary inside an embedded file. Redacting any area must remove attachments.",
            "CANARY-05", "attachment (document level)", 0, [70, 596, 300, 616]), CanaryAttachment),
        new(new(
            "canary-incremental.pdf",
            "Canary in the first revision only; an incremental update replaces it with REVISED.",
            "CANARY-06", "earlier incremental revision", 0, CanaryLineRect), CanaryIncremental),
    ];

    public static byte[] SimpleText()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        for (int i = 0; i < 3; i++)
        {
            using var page = document.AddPage(LetterWidth, LetterHeight);
            page.AddText($"Simple text page {i + 1}", 72, 720, 16);
            AddFiller(page, i, top: 690, lineCount: 40, fontSize: 11);
        }

        return Finish(document);
    }

    public static (double Width, double Height) LargePageSize(int pageIndex) =>
        pageIndex % 50 == 49 ? (595, 842)
        : pageIndex % 10 == 9 ? (792, 612)
        : (LetterWidth, LetterHeight);

    public static byte[] LargeMixed(int pageCount = LargePageCount)
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        BgraImage gradient = Gradient(128, 128);
        for (int start = 0; start < pageCount; start += ChunkSize)
        {
            using var chunk = PdfiumDocumentWriter.CreateNew();
            for (int i = start; i < Math.Min(start + ChunkSize, pageCount); i++)
            {
                var (width, height) = LargePageSize(i);
                using var page = chunk.AddPage(width, height);
                page.AddText($"Page {i + 1} of {pageCount}", 72, height - 72, 16);
                AddFiller(page, i, top: height - 100, lineCount: (int)((height - 160) / 14), fontSize: 10);
                page.AddRectangle(72, 40, 120, 12, (byte)(i * 7 % 256), 120, 200);
                page.AddRectangle(200, 40, 120, 12, 200, (byte)(i * 11 % 256), 80);
                if (i % 25 == 0)
                {
                    page.AddImage(gradient, width - 200, height - 200, 128, 128);
                }
            }

            document.ImportAllPages(chunk);
        }

        return Finish(document);
    }

    public static byte[] CanaryText()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        using (var page = AddCanaryPage(document, "Canary fixture: text"))
        {
            page.AddText("Account holder:", 72, 500, 12);
            page.AddText("CANARY-01", 180, 500, 12);
        }

        return Finish(document);
    }

    public static byte[] CanaryImage()
    {
        using var label = PdfiumDocumentWriter.CreateNew();
        using (var labelPage = label.AddPage(200, 40))
        {
            labelPage.AddText("CANARY-02", 10, 12, 24);
        }

        BgraImage pixels = label.RenderPage(0, 800, 160);

        using var document = PdfiumDocumentWriter.CreateNew();
        using (var page = AddCanaryPage(document, "Canary fixture: image"))
        {
            page.AddImage(pixels, 72, 400, 200, 40);
        }

        return Finish(document);
    }

    public static byte[] CanarySharedXObject()
    {
        using var source = PdfiumDocumentWriter.CreateNew();
        using (var sourcePage = source.AddPage(200, 40))
        {
            sourcePage.AddText("CANARY-03", 10, 12, 24);
        }

        using var document = PdfiumDocumentWriter.CreateNew();
        using var xobject = document.ImportPageAsXObject(source, 0);
        for (int i = 0; i < 2; i++)
        {
            using var page = AddCanaryPage(document, $"Canary fixture: shared XObject, page {i + 1}");
            page.AddFormXObject(xobject, 72, 600);
        }

        return Finish(document);
    }

    public static byte[] CanaryAnnotation()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        using (var page = AddCanaryPage(document, "Canary fixture: annotation"))
        {
            page.AddText("See the note:", 210, 605, 12);
            page.AddNoteAnnotation("CANARY-04", 300, 600, 320, 620);
        }

        return Finish(document);
    }

    public static byte[] CanaryAttachment()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        using (var page = AddCanaryPage(document, "Canary fixture: attachment"))
        {
            page.AddText("This document has an attachment.", 72, 600, 12);
        }

        document.AddAttachment("notes.txt", Encoding.UTF8.GetBytes("Internal note: CANARY-05"));
        return Finish(document);
    }

    public static byte[] CanaryIncremental()
    {
        byte[] original;
        using (var document = PdfiumDocumentWriter.CreateNew())
        {
            using (var page = AddCanaryPage(document, "Canary fixture: incremental revision"))
            {
                page.AddText("Original figure:", 72, 500, 12);
                page.AddText("CANARY-06", 180, 500, 12);
            }

            original = document.ToArray();
        }

        using var revised = PdfiumDocumentWriter.Load(original);
        using (var page = revised.EditPage(0))
        {
            // The canary was the last object added to the page.
            page.RemoveObjectAt(page.ObjectCount - 1);
            page.AddText("REVISED", 180, 500, 12);
        }

        return Finish(revised, PdfSaveMode.Incremental);
    }

    private static byte[] Finish(PdfiumDocumentWriter document, PdfSaveMode mode = PdfSaveMode.Full) =>
        Reproducible.Normalize(document.ToArray(mode));

    /// <summary>A Letter page with a heading and filler below y = 320, leaving 380–720 for canaries.</summary>
    private static PdfiumPageWriter AddCanaryPage(PdfiumDocumentWriter document, string heading)
    {
        var page = document.AddPage(LetterWidth, LetterHeight);
        page.AddText(heading, 72, 740, 16);
        AddFiller(page, document.PageCount, top: 300, lineCount: 15, fontSize: 11);
        return page;
    }

    private static void AddFiller(PdfiumPageWriter page, int pageIndex, double top, int lineCount, float fontSize)
    {
        double lineHeight = fontSize * 1.3;
        for (int line = 0; line < lineCount; line++)
        {
            page.AddText(FillerLine(pageIndex, line), 72, top - (line * lineHeight), fontSize);
        }
    }

    // Deterministic filler built from a fixed word list, so no fixture depends on a random seed.
    private static string FillerLine(int pageIndex, int line)
    {
        var builder = new StringBuilder();
        for (int word = 0; builder.Length < 60; word++)
        {
            if (word > 0)
            {
                builder.Append(' ');
            }

            builder.Append(Words[((pageIndex * 31) + (line * 7) + (word * 13)) % Words.Length]);
        }

        return builder.ToString();
    }

    private static BgraImage Gradient(int width, int height)
    {
        var pixels = new byte[width * height * 4];
        for (int y = 0; y < height; y++)
        {
            for (int x = 0; x < width; x++)
            {
                int offset = ((y * width) + x) * 4;
                pixels[offset] = (byte)(x * 255 / (width - 1));
                pixels[offset + 1] = (byte)(y * 255 / (height - 1));
                pixels[offset + 2] = 128;
                pixels[offset + 3] = 255;
            }
        }

        return new BgraImage(width, height, pixels);
    }
}
