    public static byte[] SimpleText()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        for (int i = 0; i < 3; i++)
        {
            using var page = document.AddPage(LetterWidth, LetterHeight);
            page.AddText($"Simple text page {i + 1}", 72, 720, 16);
            AddFiller(page, i, top: 690, lineCount: 40, fontSize: 11);
        }

        return Finish(document);
    }

    public static byte[] ImageOnlyMiddlePage()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        for (int i = 0; i < 3; i++)
        {
            using var page = document.AddPage(LetterWidth, LetterHeight);
            if (i == 1)
            {
                page.AddImage(Gradient(256, 256), 72, 72, LetterWidth - 144, LetterHeight - 144);
                continue;
            }

            page.AddText($"Text page {(i / 2) + 1}", 72, 720, 16);
            AddFiller(page, i, top: 690, lineCount: 5, fontSize: 11);
        }

        return Finish(document);
    }

    public static (double Width, double Height) LargePageSize(int pageIndex) =>
        pageIndex % 50 == 49 ? (595, 842)
        : pageIndex % 10 == 9 ? (792, 612)
        : (LetterWidth, LetterHeight);

    public static byte[] LargeMixed(int pageCount = LargePageCount)
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        BgraImage gradient = Gradient(128, 128);
        for (int start = 0; start < pageCount; start += ChunkSize)
        {
            using var chunk = PdfiumDocumentWriter.CreateNew();
            for (int i = start; i < Math.Min(start + ChunkSize, pageCount); i++)
            {
                var (width, height) = LargePageSize(i);
                using var page = chunk.AddPage(width, height);
                page.AddText($"Page {i + 1} of {pageCount}", 72, height - 72, 16);
                AddFiller(page, i, top: height - 100, lineCount: (int)((height - 160) / 14), fontSize: 10);
                page.AddRectangle(72, 40, 120, 12, (byte)(i * 7 % 256), 120, 200);
                page.AddRectangle(200, 40, 120, 12, 200, (byte)(i * 11 % 256), 80);
                if (i % 25 == 0)
                {
                    page.AddImage(gradient, width - 200, height - 200, 128, 128);
                }
            }

            document.ImportAllPages(chunk);
        }

        return Finish(document);
    }

    public static byte[] CanaryText()
    {
        using var document = PdfiumDocumentWriter.CreateNew();
        using (var page = AddCanaryPage(document, "Canary fixture: text"))
        {
            page.AddText("Account holder:", 72, 500, 12);
            page.AddText("CANARY-01", 180, 500, 12);
        }

        return Finish(document);
    }

    public static byte[] CanaryImage()
